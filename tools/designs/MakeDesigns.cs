#:package mzLib@1.0.593
#:property PublishAot=false
#:property JsonSerializerIsReflectionEnabledByDefault=true
// Curated label-free designs (G15, aging PXR-A15): one SDRF per deposit, generated from aging's per-run ages tables
// (aging instance/ages/<PXD>.tsv, written by their make_age_tables.cs; never by hand), for a question's [designs] dir.
// Each SDRF is checked by mzLib's SdrfLabelFreeDesign against the files the deposit's fetch delivered, exactly as
// DesignStage reads it before a search; a refused design is reported and not written.
//
// One factor column per SDRF, because [designs] condition_columns is one list for the whole question and mzLib refuses
// several factor columns with none declared:
//   - `factor value[age group]` = age_group (it repeats characteristics[age group], as SDRF-Proteomics expects; aging 030 PXR-A24), where the ages table's `condition` is blank throughout (age is the only factor);
//   - otherwise `factor value[group]` = design_condition (age and condition together, e.g. young_UBX0101), with
//     characteristics[age] and characteristics[treatment] carrying the parts.
// biological_replicate and technical_replicate are the ages table's; every run is fraction 1.
//
//   dotnet run MakeDesigns.cs -- --ages DIR --runs DIR --manifest manifest.yaml --out DIR
//     --ages      aging's instance/ages (one <PXD>.tsv each)
//     --runs      the run root holding <PXD>/02_fetch/fetch_manifest.json
//     --manifest  the batch manifest (each deposit's organism)
//     --out       where <PXD>.sdrf.tsv and REPORT.md go
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Readers;

var a = Args(args);
string agesDir = a["--ages"], runsDir = a["--runs"], manifest = a["--manifest"], outDir = a["--out"];
Directory.CreateDirectory(outDir);
var organisms = Organisms(File.ReadAllText(manifest));
var report = new StringBuilder();
report.AppendLine("# Curated designs from aging's ages tables").AppendLine();
report.AppendLine($"Generated by `tools/designs/MakeDesigns.cs` from `{agesDir}`; each checked by mzLib's `SdrfLabelFreeDesign` against the deposit's fetched files.").AppendLine();
report.AppendLine("| deposit | factor | conditions | files | biological replicates per condition | sdrf sha256 (12) |");
report.AppendLine("|---|---|---|---:|---|---|");
var details = new StringBuilder();
int failures = 0;

foreach (string tsv in Directory.EnumerateFiles(agesDir, "PXD*.tsv").Order(StringComparer.Ordinal))
{
    string acc = Path.GetFileNameWithoutExtension(tsv);
    var rows = ReadTsv(tsv);
    if (!organisms.TryGetValue(acc, out string? organism)) throw new InvalidOperationException($"{acc}: no organism in {manifest}");
    bool ageOnly = rows.All(r => r["condition"].Length == 0);
    if (ageOnly && rows.Any(r => r["design_condition"] != r["age_group"]))
        throw new InvalidOperationException($"{acc}: condition is blank but design_condition differs from age_group");
    string factor = ageOnly ? "factor value[age group]" : "factor value[group]";

    var sb = new StringBuilder();
    sb.Append("source name\tcharacteristics[organism]\tcharacteristics[age]\tcharacteristics[age group]\t");
    sb.Append(ageOnly ? "" : "characteristics[treatment]\t");
    sb.Append("characteristics[biological replicate]\tassay name\tcomment[label]\tcomment[data file]\t");
    sb.Append($"comment[technical replicate]\tcomment[fraction identifier]\t{factor}\n");
    int n = 0;
    foreach (var r in rows)
    {
        n++;
        sb.Append($"{acc}-{r["animal"]}\t{organism}\t{r["age_months"]} months\t{r["age_group"]}\t");
        if (!ageOnly) sb.Append(r["condition"]).Append('\t');
        sb.Append($"{r["biological_replicate"]}\trun {n}\tlabel free sample\t{r["file"]}\t");
        sb.Append($"{r["technical_replicate"]}\t1\t{(ageOnly ? r["age_group"] : r["design_condition"])}\n");
    }
    string sdrf = Path.Combine(outDir, $"{acc}.sdrf.tsv");
    string staged = sdrf + ".tmp";
    File.WriteAllText(staged, sb.ToString(), new UTF8Encoding(false));

    string fetchManifest = Path.Combine(runsDir, acc, "02_fetch", "fetch_manifest.json");
    var fetched = JsonDocument.Parse(File.ReadAllText(fetchManifest)).RootElement.GetProperty("files")
        .EnumerateArray().Select(f => f.GetProperty("file").GetString()!).ToList();
    var missing = fetched.Select(Path.GetFileName).Except(rows.Select(r => r["file"]), StringComparer.Ordinal).ToList();
    var d = SdrfLabelFreeDesign.Read(staged, new SdrfLabelFreeDesignOptions { SearchedFiles = fetched });

    details.AppendLine($"## {acc}").AppendLine().AppendLine("```").Append(d.Report()).AppendLine("```");
    if (missing.Count > 0) details.AppendLine($"Fetched but not in the ages table: {string.Join(", ", missing)}");
    details.AppendLine();
    if (!d.IsValid || missing.Count > 0)
    {
        failures++;
        File.Delete(staged);
        File.Delete(sdrf);
        report.AppendLine($"| {acc} | REFUSED | | | | |");
        Console.Error.WriteLine($"{acc}: REFUSED ({d.Refusals.Count} refusals, {missing.Count} fetched files without a row)");
        continue;
    }
    File.Move(staged, sdrf, overwrite: true);
    var perCondition = d.Files.GroupBy(f => f.Condition).OrderBy(g => g.Key, StringComparer.Ordinal)
        .Select(g => $"{g.Key} {g.Select(f => f.BiologicalReplicate).Distinct().Count()}");
    report.AppendLine($"| {acc} | `{factor}` | {d.Files.Select(f => f.Condition).Distinct().Count()} | {d.Files.Count} | {string.Join(", ", perCondition)} | {Sha(sdrf)[..12]} |");
    Console.Error.WriteLine($"{acc}: ok, {d.Files.Count} files, {factor}");
}
report.AppendLine().Append(details);
File.WriteAllText(Path.Combine(outDir, "REPORT.md"), report.ToString(), new UTF8Encoding(false));
return failures == 0 ? 0 : 1;

static List<Dictionary<string, string>> ReadTsv(string path)
{
    var lines = File.ReadAllLines(path).Where(l => !l.StartsWith('#') && l.Length > 0).ToList();
    string[] header = lines[0].Split('\t');
    return lines.Skip(1).Select(l =>
    {
        string[] v = l.Split('\t');
        if (v.Length != header.Length) throw new InvalidOperationException($"{path}: a row has {v.Length} fields, the header {header.Length}");
        return header.Zip(v).ToDictionary(p => p.First, p => p.Second.Trim(), StringComparer.Ordinal);
    }).ToList();
}

// The batch manifest's `organism: NCBITaxon:<id>` per accession; only the three organisms the profiles search.
static Dictionary<string, string> Organisms(string yaml)
{
    var names = new Dictionary<string, string> { ["9606"] = "Homo sapiens", ["10090"] = "Mus musculus", ["10116"] = "Rattus norvegicus" };
    var result = new Dictionary<string, string>(StringComparer.Ordinal);
    string? acc = null;
    foreach (string line in yaml.Split('\n'))
    {
        var m = Regex.Match(line, @"^\s*- accession:\s*(PXD\d+)");
        if (m.Success) { acc = m.Groups[1].Value; continue; }
        m = Regex.Match(line, @"^\s+organism:\s*NCBITaxon:(\d+)");
        if (m.Success && acc is not null && names.TryGetValue(m.Groups[1].Value, out string? name)) result[acc] = name;
    }
    return result;
}

static string Sha(string path)
{
    using var s = File.OpenRead(path);
    return Convert.ToHexStringLower(SHA256.HashData(s));
}

static Dictionary<string, string> Args(string[] args)
{
    var d = new Dictionary<string, string>(StringComparer.Ordinal);
    for (int i = 0; i + 1 < args.Length; i += 2) d[args[i]] = args[i + 1];
    foreach (string k in new[] { "--ages", "--runs", "--manifest", "--out" })
        if (!d.ContainsKey(k)) throw new ArgumentException($"missing {k}");
    return d;
}
